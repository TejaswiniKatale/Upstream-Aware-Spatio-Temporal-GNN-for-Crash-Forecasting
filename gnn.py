class CausalTemporalConv(nn.Module):
    """
    Causal conv along time only.
    x: (B,N,C,T)
    returns: (B,N,C_out,T)
    """
    def __init__(self, c_in, c_out, k_t=3, dilation=1):
        super().__init__()
        self.k_t = k_t
        self.dilation = dilation
        self.conv = nn.Conv2d(
            in_channels=c_in,
            out_channels=c_out,
            kernel_size=(1, k_t),
            dilation=(1, dilation),
            padding=0
        )

    def forward(self, x):
        # left pad only (causal)
        pad_left = (self.k_t - 1) * self.dilation
        x = F.pad(x, (pad_left, 0, 0, 0))  # pad time dim only: (left,right,top,bottom) for last 2 dims
        return self.conv(x)

class SpatialGCN(nn.Module):
    """
    Spatial graph conv using sparse normalized adjacency.
    x: (B,N,C,T)
    do: for each (B,T), X' = A_norm @ X
    """
    def __init__(self, c_in, c_out, A_norm_sparse):
        super().__init__()
        self.A = A_norm_sparse
        self.lin = nn.Linear(c_in, c_out, bias=False)

    def forward(self, x):
        B, Nn, C, Tt = x.shape
        # (B,T,N,C)
        x_bt = x.permute(0, 3, 1, 2).contiguous()
        x_bt = self.lin(x_bt)  # (B,T,N,Cout)

        outs = []
        for b in range(B):
            # for each time, sparse mm: (N,N)@(N,C)
            xb = x_bt[b]  # (T,N,Cout)
            xb_out = []
            for t in range(Tt):
                xb_out.append(torch.sparse.mm(self.A, xb[t]))  # (N,Cout)
            outs.append(torch.stack(xb_out, dim=0))  # (T,N,Cout)

        out = torch.stack(outs, dim=0)  # (B,T,N,Cout)
        out = out.permute(0, 2, 3, 1).contiguous()  # (B,N,Cout,T)
        return out

class STGCNBlock(nn.Module):
    def __init__(self, c_in, c_mid, c_out, A_norm_sparse, k_t=3, dilation=1, dropout=0.1):
        super().__init__()
        self.t1 = CausalTemporalConv(c_in, c_mid, k_t=k_t, dilation=dilation)
        self.gcn = SpatialGCN(c_mid, c_mid, A_norm_sparse)
        self.t2 = CausalTemporalConv(c_mid, c_out, k_t=k_t, dilation=1)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x):
        # x: (B, N, C, T)

        # ---- Temporal 1 ----
        x = x.permute(0, 2, 1, 3).contiguous()   # (B, C, N, T)
        x = F.relu(self.t1(x))                  # (B, Cmid, N, T)
        x = x.permute(0, 2, 1, 3).contiguous()  # (B, N, Cmid, T)

        # ---- Spatial ----
        x = F.relu(self.gcn(x))                 # (B, N, Cmid, T)
        x = self.dropout(x)

        # ---- Temporal 2 ----
        x = x.permute(0, 2, 1, 3).contiguous()  # (B, Cmid, N, T)
        x = F.relu(self.t2(x))                  # (B, Cout, N, T)
        x = x.permute(0, 2, 1, 3).contiguous()  # (B, N, Cout, T)

        return x


class STGCN(nn.Module):
    def __init__(self, Fdim, A_norm_sparse, hidden=64, k_t=3, blocks=2):
        super().__init__()
        self.in_proj = nn.Conv2d(Fdim, hidden, kernel_size=(1, 1))
        self.blocks = nn.ModuleList()
        for b in range(blocks):
            self.blocks.append(STGCNBlock(hidden, hidden, hidden, A_norm_sparse, k_t=k_t, dilation=1, dropout=0.1))
        self.head = nn.Conv2d(hidden, 1, kernel_size=(1, 1))  # per-node per-time
    def forward(self, Xseq):
        # Xseq: (N,T,F) -> (1,N,F,T)
        x = Xseq.permute(0, 2, 1).unsqueeze(0).contiguous()  # (1,N,F,T)? actually (1,N,F,T) after permute?:
        # Xseq (N,T,F) permute(0,2,1) => (N,F,T), unsqueeze => (1,N,F,T)
        # Conv2d expects (B,C,H,W). We'll treat H=N and W=T, so channels=F
        x = x.permute(0, 2, 1, 3).contiguous()  # (B,F,N,T)
        x = self.in_proj(x)                     # (B,Hid,N,T)
        x = x.permute(0, 2, 1, 3).contiguous()  # (B,N,Hid,T)

        for blk in self.blocks:
            x = blk(x)  # (B,N,Hid,T)

        # head expects (B,C,N,T)
        xh = x.permute(0, 2, 1, 3).contiguous()  # (B,Hid,N,T)
        yhat = self.head(xh)                      # (B,1,N,T)
        yhat = yhat.squeeze(1).squeeze(0)         # (N,T)
        # next-step predictions at times 0..T-2 correspond to output at times 0..T-2
        # return (N,T-1)
        return F.softplus(yhat[:, :-1])

