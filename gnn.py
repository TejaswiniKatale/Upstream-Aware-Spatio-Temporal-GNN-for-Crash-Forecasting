class RoadSpatialLayer(nn.Module):
    def __init__(self, dim, neighbors, upstream):
        super().__init__()
        self.neighbors = neighbors
        self.upstream = upstream

        #Attention projections
        self.W_q = nn.Linear(dim, dim)   #query -> current segment
        self.W_k = nn.Linear(dim, dim)   #key -> Upstream segment
        self.W_v = nn.Linear(dim, dim)   #value -> Upstream segment

        self.a = nn.Linear(dim * 2, 1)   # Computes raw attention [current segment || upstream segment]
        self.W_base = nn.Linear(dim * 2, dim)  #Final layer [own features || spatial message] -> new features
        self.w_g = nn.Linear(dim * 3, 1)  # [own_features || neighbor_message || upstream_message], how much upstream influence should matter [gate g ∈ (0,1)]


        #Activations
        self.act = nn.ReLU()  #Relu (-3, -> 0, 2-> 2)
        self.sigmoid = nn.Sigmoid()
        self.leaky = nn.LeakyReLU(0.2)  # negatuve values are scaled down (0.2 * -0.3)


   #forward pass
    def forward(self, h):
        N, d = h.shape #h input feature for 1 month  (N-> no of road segments, d-> Dimension of embeddings (64))

        m_base = torch.zeros((N, d), device=h.device) #the graophsage
        m_up = torch.zeros((N, d), device=h.device) #upstream

        for i in range(N):  #The graphsage, summarize what the neighbours tell
            if len(self.neighbors[i]) > 0:
                m_base[i] = h[self.neighbors[i]].mean(dim=0)   #avg embedding

            ups = self.upstream[i] #list of upstream indices for segment i
            if len(ups) > 0:
                qi = self.W_q(h[i])  #query
                hj = h[ups]   #collect embeddings from all the upstreams
                kj = self.W_k(hj)   #compute keys (key vectors)

                qi_rep = qi.unsqueeze(0).expand(len(ups), -1)
                e = self.leaky(self.a(torch.cat([qi_rep, kj], dim=1))).view(-1)  #Compute raw attention scores #concat (Query, key)
                alpha = torch.softmax(e, dim=0) #converts raw scores into weights

                vj = self.W_v(hj) ##Transforms into value vectors
                m_up[i] = torch.sum(alpha[:, None] * vj, dim=0)  #Upstream vector * its weight -> sum all

        g = self.sigmoid(self.w_g(torch.cat([h, m_base, m_up], dim=1)))  #Gates
        h_out = self.W_base(torch.cat([h, m_base + g * m_up], dim=1))   #how much should upstream matter? g: (0 to 1)
        return self.act(h_out)  #Applies Relu, removes negative noise


class STGNN(nn.Module):
    def __init__(self, Fdim, gnn_dim, gnn_layers, gru_dim, neighbors, upstream):
        super().__init__()
        self.in_proj = nn.Linear(Fdim, gnn_dim) #converts raw features → learned embedding space



# Layer 1 → immediate neighbors + upstream
# Layer 2 → neighbors of neighbors + farther upstream
# Layer 3 → even wider spatial influence

        self.layers = nn.ModuleList([ #creates the gnn layers
            RoadSpatialLayer(gnn_dim, neighbors, upstream)
            for _ in range(gnn_layers)
        ])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)  #GRU Layer
        self.out = nn.Linear(gru_dim, 1)  #Converts GRU hidden state → predicted crash value, # One scalar per segment per time step

    def forward(self, Xseq):
        N, Tseq, _ = Xseq.shape
        Hs = []


        # Each layer-> mixes neighbors-> applies upstream attention -> applies gating
        for t in range(Tseq):
            h = self.in_proj(Xseq[:, t, :])  #Takes features of all segments at month t
            for layer in self.layers: #3 layers we defined
                h = layer(h)  #h = spatially-enriched embeddings for month t
            Hs.append(h.unsqueeze(1))

        H = torch.cat(Hs, dim=1)
        Ht, _ = self.gru(H)
        y_hat = self.out(Ht[:, :-1, :]).squeeze(-1)  #predict next month only
        return F.softplus(y_hat)

