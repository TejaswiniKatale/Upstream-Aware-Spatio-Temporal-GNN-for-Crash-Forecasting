class RoadSpatialLayer(nn.Module):
    def __init__(self, dim):
        super().__init__()
        # upstream attention projections
        self.Wq = nn.Linear(dim, dim)
        self.Wk = nn.Linear(dim, dim)
        self.Wv = nn.Linear(dim, dim)

        # two gates
        self.g_base = nn.Linear(dim * 2, 1)  # [h || m_base]
        self.g_up   = nn.Linear(dim * 2, 1)  # [h || m_up]

        # combine
        self.Wo = nn.Linear(dim * 2, dim)

        self.ln = nn.LayerNorm(dim)
        self.act = nn.ReLU()

    def forward(self, h):
        Nn, d = h.shape
        mb = torch.zeros_like(h)
        mu = torch.zeros_like(h)

        for i in range(Nn):
            if neighbors[i]:
                mb[i] = h[neighbors[i]].mean(dim=0)

            ups = upstream[i]
            if ups:
                qi = self.Wq(h[i])        # (d,)
                hj = h[ups]               # (U,d)
                kj = self.Wk(hj)          # (U,d)
                scores = (qi.unsqueeze(0) * kj).sum(dim=1)  # (U,)
                alpha = torch.softmax(scores, dim=0)
                vj = self.Wv(hj)
                mu[i] = (alpha[:, None] * vj).sum(dim=0)

        gb = torch.sigmoid(self.g_base(torch.cat([h, mb], dim=1)))  # (N,1)
        gu = torch.sigmoid(self.g_up(torch.cat([h, mu], dim=1)))    # (N,1)

        spatial_msg = gb * mb + gu * mu
        h_new = self.Wo(torch.cat([h, spatial_msg], dim=1))
        h_out = self.ln(h + h_new)
        return self.act(h_out)

class STGNN(nn.Module):
    def __init__(self, F_dim, gnn_dim=64, gnn_layers=2, gru_dim=96, out_tau=0.7):
        super().__init__()
        self.inp = nn.Linear(F_dim, gnn_dim)
        self.gnn = nn.ModuleList([RoadSpatialLayer(gnn_dim) for _ in range(gnn_layers)])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)
        self.out = nn.Linear(gru_dim, 1)
        self.out_tau = out_tau  # <1 increases spread a bit (helps ranking)

    def forward(self, Xseq):
        Nn, Tseq, _ = Xseq.shape
        Hs = []
        for t in range(Tseq):
            h = self.inp(Xseq[:, t, :])
            for layer in self.gnn:
                h = layer(h)
            Hs.append(h.unsqueeze(1))

        H = torch.cat(Hs, dim=1)             # (N,Tseq,gnn_dim)
        Ht, _ = self.gru(H)                  # (N,Tseq,gru_dim)
        y_hat = self.out(Ht[:, :-1, :]).squeeze(-1)  # (N,Tseq-1)

        # Predict LOG1P(crashes_next_month) as a nonnegative quantity
        # tau < 1 increases separation a bit (still stable)
        return F.softplus(y_hat / self.out_tau)

