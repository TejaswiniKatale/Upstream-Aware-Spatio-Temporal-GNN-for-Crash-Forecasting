# 5) MODEL: Spatial GCN per month + GRU + ZINB heads
# =========================================================
class SpatialGCNLayer(nn.Module):
    def __init__(self, in_dim, out_dim, A_norm_sparse, dropout=0.1):
        super().__init__()
        self.A = A_norm_sparse
        self.lin = nn.Linear(in_dim, out_dim, bias=False)
        self.dropout = nn.Dropout(dropout)

    def forward(self, h):
        # h: (N, in_dim)
        h = self.dropout(h)
        h = self.lin(h)                # (N,out_dim)
        h = torch.sparse.mm(self.A, h) # (N,out_dim)
        return F.relu(h)

class STZINBGNN(nn.Module):
    def __init__(self, Fdim, A_norm_sparse, gnn_dim=64, gnn_layers=2, gru_dim=64, dropout=0.1):
        super().__init__()
        self.in_proj = nn.Linear(Fdim, gnn_dim)
        self.gnn = nn.ModuleList([
            SpatialGCNLayer(gnn_dim, gnn_dim, A_norm_sparse, dropout=dropout)
            for _ in range(gnn_layers)
        ])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)

        # Heads for ZINB parameters for NEXT MONTH
        self.pi_head = nn.Linear(gru_dim, 1)      # -> sigmoid
        self.mu_head = nn.Linear(gru_dim, 1)      # -> softplus
        self.th_head = nn.Linear(gru_dim, 1)      # -> softplus (dispersion)

    def spatial_encode(self, x_t):
        # x_t: (N,F)
        h = F.relu(self.in_proj(x_t))
        for layer in self.gnn:
            h = layer(h)
        return h  # (N,gnn_dim)

    def forward(self, Xseq):
        # Xseq: (N,Tseq,F)
        Nn, Tseq, _ = Xseq.shape

        Hs = []
        for t in range(Tseq):
            ht = self.spatial_encode(Xseq[:, t, :]).unsqueeze(1)  # (N,1,gnn_dim)
            Hs.append(ht)
        Hs = torch.cat(Hs, dim=1)  # (N,Tseq,gnn_dim)

        H, _ = self.gru(Hs)        # (N,Tseq,gru_dim)

        # Predict y_{t+1} using hidden at time t, for t=0..Tseq-2
        H_pred = H[:, :-1, :]      # (N,Tseq-1,gru_dim)

        pi    = torch.sigmoid(self.pi_head(H_pred)).squeeze(-1)        # (N,Tseq-1)
        mu    = F.softplus(self.mu_head(H_pred)).squeeze(-1) + 1e-6    # (N,Tseq-1)
        theta = F.softplus(self.th_head(H_pred)).squeeze(-1) + 1e-6    # (N,Tseq-1)

        return pi, mu, theta

