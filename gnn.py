def ranking_loss(y_pred_log, y_true_count, margin=0.2):
    """
    Pairwise ranking loss in LOG space.
    Push (crash-positive) segments above (zero-crash) segments.
    y_pred_log: (N, T)
    y_true_count: (N, T) raw counts, used only for pos/neg masks
    """
    loss = 0.0
    cnt = 0
    for t in range(y_pred_log.shape[1]):
        yp = y_pred_log[:, t]
        yt = y_true_count[:, t]

        pos = yp[yt > 0]
        neg = yp[yt == 0]

        if pos.numel() == 0 or neg.numel() == 0:
            continue

        # sample negatives to keep it cheap and balanced
        k = min(pos.numel(), neg.numel())
        neg = neg[torch.randperm(neg.numel(), device=neg.device)[:k]]
        pos = pos[torch.randperm(pos.numel(), device=pos.device)[:k]]

        # want pos >= neg + margin
        loss = loss + torch.mean(torch.relu(margin - pos.unsqueeze(1) + neg.unsqueeze(0)))
        cnt += 1

    return loss / max(cnt, 1)

