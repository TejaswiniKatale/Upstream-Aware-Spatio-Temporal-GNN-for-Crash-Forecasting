def parse_prefix(seg):
    p = str(seg).split("_")
    return "_".join(p[:-2]) if len(p) >= 3 else str(seg)

def parse_begin(seg):
    try:
        return float(str(seg).split("_")[-2])
    except:
        return 0.0

static = pd.DataFrame({"SEGMENT_KEY": segments})
static["PREFIX"] = static["SEGMENT_KEY"].apply(parse_prefix)
static["BEGIN"] = static["SEGMENT_KEY"].apply(parse_begin)

neighbors = [[] for _ in range(N)]
upstream = [[] for _ in range(N)]

for _, g in static.groupby("PREFIX"):
    g = g.sort_values("BEGIN")
    idxs = [seg2idx[s] for s in g["SEGMENT_KEY"]]

    for i in range(len(idxs) - 1):
        neighbors[idxs[i]].append(idxs[i + 1])
        neighbors[idxs[i + 1]].append(idxs[i])

    for i in range(len(idxs)):
        upstream[idxs[i]].extend(idxs[:i])

neighbors = [list(set(n)) for n in neighbors]
upstream = [list(set(u)) for u in upstream]

# =========================================================
# 5. BUILD X, y (LAG FEATURE)
# =========================================================
numeric_cols = [
    c for c in df.select_dtypes(include=[np.number]).columns
    if c not in ["TOTAL_CRASHES", "YEAR_QUARTER", "YEAR_HALF"]
]

train_T, val_T, test_T = 24, 6, 6
train_end = months_all[train_T - 1]

# normalize using TRAIN months only
for c in numeric_cols:
    mu = df[df["YEAR_MONTH"] <= train_end][c].mean()
    sd = df[df["YEAR_MONTH"] <= train_end][c].std()
    if sd > 0:
        df[c] = (df[c] - mu) / sd
    else:
        df[c] = df[c] - mu

F_dim = len(numeric_cols) + 1
month2idx = {m: i for i, m in enumerate(months_all)}

y = np.zeros((N, T), dtype=np.float32)
for _, r in df.iterrows():
    y[seg2idx[r["SEGMENT_KEY"]], month2idx[r["YEAR_MONTH"]]] = r["TOTAL_CRASHES"]

X = np.zeros((N, T, F_dim), dtype=np.float32)
for _, r in df.iterrows():
    i = seg2idx[r["SEGMENT_KEY"]]
    t = month2idx[r["YEAR_MONTH"]]
    X[i, t, :-1] = r[numeric_cols].values
    X[i, t, -1] = y[i, t-1] if t > 0 else 0.0

X_torch = torch.tensor(X).to(device)
y_torch = torch.tensor(y).to(device)

