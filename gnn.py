class SpatialGAT(nn.Module):
    """
    Single-head GAT over the neighbor list.
    h_i' = ReLU(W h_i + sum_j alpha_ij * W h_j)
    alpha_ij = softmax_j( LeakyReLU( a^T [W h_i || W h_j] ) )
    """
    def __init__(self, dim, neighbors):
        super().__init__()
        self.neighbors = neighbors
        self.W = nn.Linear(dim, dim, bias=False)
        self.a = nn.Linear(2*dim, 1, bias=False)
        self.leaky = nn.LeakyReLU(0.2)

    def forward(self, h):
        # h: (N, dim)
        N, d = h.shape
        Wh = self.W(h)  # (N,d)

        out = torch.zeros((N, d), device=h.device)
        for i in range(N):
            nei = self.neighbors[i]
            if len(nei) == 0:
                out[i] = Wh[i]
                continue

            Wh_i = Wh[i].unsqueeze(0).expand(len(nei), -1)   # (k,d)
            Wh_j = Wh[nei]                                   # (k,d)
            e = self.leaky(self.a(torch.cat([Wh_i, Wh_j], dim=1))).view(-1)  # (k,)
            alpha = torch.softmax(e, dim=0)                                  # (k,)
            out[i] = Wh[i] + torch.sum(alpha[:, None] * Wh_j, dim=0)

        return F.relu(out)

class TASTAN(nn.Module):
    def __init__(self, Fdim, gnn_dim=64, gru_dim=64, gnn_layers=2):
        super().__init__()
        self.in_proj = nn.Linear(Fdim, gnn_dim)

        self.spatial_layers = nn.ModuleList([SpatialGAT(gnn_dim, neighbors) for _ in range(gnn_layers)])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)

        # temporal attention: dot-product (query = h_t, keys = h_0..h_t)
        self.out = nn.Linear(gru_dim, 1)

    def spatial_encode(self, x_t):
        h = F.relu(self.in_proj(x_t))
        for layer in self.spatial_layers:
            h = layer(h)
        return h

    def forward(self, Xseq):
        # Xseq: (N, Tseq, F)
        Nn, Tseq, _ = Xseq.shape

        # spatial per time
        Hs = []
        for t in range(Tseq):
            Hs.append(self.spatial_encode(Xseq[:, t, :]).unsqueeze(1))
        Hs = torch.cat(Hs, dim=1)  # (N,Tseq,gnn_dim)

        # temporal GRU
        H, _ = self.gru(Hs)        # (N,Tseq,gru_dim)

        # predict next step for t=0..Tseq-2
        preds = []
        for t in range(Tseq - 1):
            # keys/values: 0..t, query: t
            keys = H[:, :t+1, :]            # (N,t+1,d)
            q = H[:, t, :].unsqueeze(2)     # (N,d,1)
            scores = torch.bmm(keys, q).squeeze(2)  # (N,t+1)
            alpha = torch.softmax(scores, dim=1)    # (N,t+1)
            context = torch.sum(keys * alpha.unsqueeze(2), dim=1)  # (N,d)
            preds.append(self.out(context).squeeze(1).unsqueeze(1)) # (N,1)

        preds = torch.cat(preds, dim=1)     # (N,Tseq-1)
        return F.softplus(preds)

