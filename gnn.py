class RoadSpatialLayer(nn.Module):
    """
    Input:  h  (N, d)  for ONE month
    Output: h' (N, d)  spatially mixed representation
    """
    def __init__(self, dim):
        super().__init__()
        # upstream attention projections
        self.Wq = nn.Linear(dim, dim)
        self.Wk = nn.Linear(dim, dim)
        self.Wv = nn.Linear(dim, dim)

        # TWO gates:
        # - g_base controls GraphSAGE neighbor message
        # - g_up controls upstream attention message
        self.g_base = nn.Linear(dim * 2, 1)  # [h || m_base] -> scalar
        self.g_up   = nn.Linear(dim * 2, 1)  # [h || m_up]   -> scalar

        # combine [h || spatial_msg] -> new h
        self.Wo = nn.Linear(dim * 2, dim)

        # stability
        self.ln = nn.LayerNorm(dim)
        self.act = nn.ReLU()

    def forward(self, h):
        Nn, d = h.shape
        mb = torch.zeros_like(h)  # neighbor mean message
        mu = torch.zeros_like(h)  # upstream attention message

        # build messages per segment
        for i in range(Nn):
            # GraphSAGE neighbor mean
            if neighbors[i]:
                mb[i] = h[neighbors[i]].mean(dim=0)

            # upstream attention
            ups = upstream[i]
            if ups:
                qi = self.Wq(h[i])          # (d,)
                hj = h[ups]                # (U,d)
                kj = self.Wk(hj)           # (U,d)

                # dot-product score per upstream segment (U,)
                # (qi * kj).sum(1) is a simple similarity score
                scores = (qi.unsqueeze(0) * kj).sum(dim=1)
                alpha = torch.softmax(scores, dim=0)

                vj = self.Wv(hj)           # (U,d)
                mu[i] = (alpha[:, None] * vj).sum(dim=0)

        # gates (vectorized across all segments)
        gb = torch.sigmoid(self.g_base(torch.cat([h, mb], dim=1)))  # (N,1)
        gu = torch.sigmoid(self.g_up(torch.cat([h, mu], dim=1)))    # (N,1)

        spatial_msg = gb * mb + gu * mu                              # (N,d)

        h_new = self.Wo(torch.cat([h, spatial_msg], dim=1))          # (N,d)
        h_out = self.ln(h + h_new)                                   # residual + norm
        return self.act(h_out)

class STGNN(nn.Module):
    def __init__(self, F_dim, gnn_dim=64, gnn_layers=2, gru_dim=96):
        super().__init__()
        self.inp = nn.Linear(F_dim, gnn_dim)
        self.gnn = nn.ModuleList([RoadSpatialLayer(gnn_dim) for _ in range(gnn_layers)])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)
        self.out = nn.Linear(gru_dim, 1)

    def forward(self, Xseq):
        # Xseq: (N, Tseq, F_dim)
        Nn, Tseq, _ = Xseq.shape
        Hs = []
        for t in range(Tseq):
            h = self.inp(Xseq[:, t, :])        # (N,gnn_dim)
            for layer in self.gnn:
                h = layer(h)                  # (N,gnn_dim)
            Hs.append(h.unsqueeze(1))         # (N,1,gnn_dim)

