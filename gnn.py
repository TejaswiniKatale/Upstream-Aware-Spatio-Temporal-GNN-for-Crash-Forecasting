# 4) ZINB NEGATIVE LOG-LIKELIHOOD (stable)
# =========================================================
def zinb_nll(y_true, mu, theta, pi, eps=1e-8):
    """
    y_true: (...,) non-negative counts
    mu:     (...,) mean > 0
    theta:  (...,) dispersion > 0  (often called 'r' or 'alpha^-1')
    pi:     (...,) zero-inflation prob in (0,1)

    NB pmf with mean mu and dispersion theta:
      p = theta / (theta + mu)
      log NB(k) = lgamma(k+theta)-lgamma(theta)-lgamma(k+1)
                  + theta*log(p) + k*log(1-p)
    ZINB:
      if k==0: log( pi + (1-pi)*NB(0) )
      else:    log(1-pi) + log NB(k)
    """
    y_true = y_true.float()
    mu = mu.clamp(min=eps)
    theta = theta.clamp(min=eps)
    pi = pi.clamp(min=eps, max=1.0-eps)

    # NB log-prob
    t1 = torch.lgamma(y_true + theta) - torch.lgamma(theta) - torch.lgamma(y_true + 1.0)
    t2 = theta * (torch.log(theta + eps) - torch.log(theta + mu + eps))
    t3 = y_true * (torch.log(mu + eps) - torch.log(theta + mu + eps))
    log_nb = t1 + t2 + t3  # (...,)

    # NB prob at zero: exp(log_nb) with y_true=0 -> log_nb_zero
    log_nb_zero = (
        torch.lgamma(theta) - torch.lgamma(theta) - torch.lgamma(torch.tensor(1.0, device=y_true.device)) +
        theta * (torch.log(theta + eps) - torch.log(theta + mu + eps))
    )  # simplifies but keep stable form
    # Actually for y=0, log_nb = theta*(log(theta)-log(theta+mu))
    log_nb_zero = theta * (torch.log(theta + eps) - torch.log(theta + mu + eps))

    is_zero = (y_true < 0.5)

    # log P(y=0) = log( pi + (1-pi)*exp(log_nb_zero) )
    log_p_zero = torch.log(pi + (1.0 - pi) * torch.exp(log_nb_zero) + eps)

    # log P(y>0) = log(1-pi) + log_nb
    log_p_nonzero = torch.log(1.0 - pi + eps) + log_nb

    log_p = torch.where(is_zero, log_p_zero, log_p_nonzero)
    return -torch.mean(log_p)

