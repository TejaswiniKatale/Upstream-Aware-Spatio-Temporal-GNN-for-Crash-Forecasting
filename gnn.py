# 6. MODEL (ALL BUGS FIXED)
# =========================================================
class RoadSpatialLayer(nn.Module):
    def __init__(self, d, neighbors, upstream, dropout):
        super().__init__()
        self.neighbors = neighbors
        self.upstream = upstream

        self.Wq = nn.Linear(d, d)
        self.Wk = nn.Linear(d, d)
        self.Wv = nn.Linear(d, d)

        self.a = nn.Linear(2*d, 1)
        self.Wb = nn.Linear(2*d, d)
        self.gate = nn.Linear(3*d, 1)

        self.act = nn.ReLU()
        self.drop = nn.Dropout(dropout)
        self.leaky = nn.LeakyReLU(0.2)

    def forward(self, h):
        N, d = h.shape
        mb = torch.zeros_like(h)
        mu = torch.zeros_like(h)

        for i in range(N):
            if self.neighbors[i]:
                mb[i] = h[self.neighbors[i]].mean(0)

            if self.upstream[i]:
                qi = self.Wq(h[i])
                hj = h[self.upstream[i]]
                kj = self.Wk(hj)

                qi_rep = qi.unsqueeze(0).expand(len(hj), -1)
                e = self.a(torch.cat([qi_rep, kj], 1))
                e = self.leaky(e).view(-1)   # ✅ FIX

                a = torch.softmax(e, 0)
                mu[i] = (a[:, None] * self.Wv(hj)).sum(0)

        g = torch.sigmoid(self.gate(torch.cat([h, mb, mu], 1)))
        out = self.Wb(torch.cat([h, mb + g*mu], 1))
        return self.drop(self.act(out))

class STGNN(nn.Module):
    def __init__(self, F, gnn, gru, dropout):
        super().__init__()
        self.inp = nn.Linear(F, gnn)
        self.layers = nn.ModuleList([
            RoadSpatialLayer(gnn, neighbors, upstream, dropout)
            for _ in range(2)
        ])
        self.gru = nn.GRU(gnn, gru, batch_first=True)
        self.drop = nn.Dropout(dropout)
        self.out = nn.Linear(gru, 1)

    def forward(self, X):
        Hs = []
        for t in range(X.shape[1]):
            h = self.inp(X[:, t])
            for l in self.layers:
                h = l(h)
            Hs.append(h.unsqueeze(1))

        H = torch.cat(Hs, 1)
        Ht, _ = self.gru(H)
        return F.softplus(self.out(self.drop(Ht[:, :-1])).squeeze(-1))

