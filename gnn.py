class RoadSpatialLayer(nn.Module):
    def __init__(self, dim, neighbors, upstream, dropout=0.3):
        super().__init__()
        self.neighbors = neighbors
        self.upstream = upstream

        self.W_q = nn.Linear(dim, dim)
        self.W_k = nn.Linear(dim, dim)
        self.W_v = nn.Linear(dim, dim)

        self.a = nn.Linear(dim * 2, 1)
        self.W_base = nn.Linear(dim * 2, dim)
        self.w_g = nn.Linear(dim * 3, 1)

        self.act = nn.ReLU()
        self.sigmoid = nn.Sigmoid()
        self.leaky = nn.LeakyReLU(0.2)
        self.drop = nn.Dropout(dropout)

    def forward(self, h):
        N, d = h.shape

        m_base = torch.zeros((N, d), device=h.device)
        m_up = torch.zeros((N, d), device=h.device)

        for i in range(N):
            # base neighbor mean aggregation
            if len(self.neighbors[i]) > 0:
                m_base[i] = h[self.neighbors[i]].mean(dim=0)

            # upstream attention aggregation
            ups = self.upstream[i]
            if len(ups) > 0:
                qi = self.W_q(h[i])
                hj = h[ups]
                kj = self.W_k(hj)

                qi_rep = qi.unsqueeze(0).expand(len(ups), -1)
                e = self.leaky(self.a(torch.cat([qi_rep, kj], dim=1))).view(-1)
                alpha = torch.softmax(e, dim=0)

                vj = self.W_v(hj)
                m_up[i] = torch.sum(alpha[:, None] * vj, dim=0)

        # gated fusion
        g = self.sigmoid(self.w_g(torch.cat([h, m_base, m_up], dim=1)))
        h_out = self.W_base(torch.cat([h, m_base + g * m_up], dim=1))
        h_out = self.act(h_out)
        h_out = self.drop(h_out)
        return h_out

class STGNN(nn.Module):
    def __init__(self, Fdim, gnn_dim, gnn_layers, gru_dim, neighbors, upstream, dropout=0.3):
        super().__init__()
        self.in_proj = nn.Linear(Fdim, gnn_dim)
        self.layers = nn.ModuleList([
            RoadSpatialLayer(gnn_dim, neighbors, upstream, dropout=dropout)
            for _ in range(gnn_layers)
        ])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)
        self.drop = nn.Dropout(dropout)
        self.out = nn.Linear(gru_dim, 1)

    def forward(self, Xseq):
        N, Tseq, _ = Xseq.shape
        Hs = []
        for t in range(Tseq):
            h = self.in_proj(Xseq[:, t, :])
            for layer in self.layers:
                h = layer(h)
            Hs.append(h.unsqueeze(1))

        H = torch.cat(Hs, dim=1)  # (N,Tseq,gnn_dim)
        Ht, _ = self.gru(H)
        Ht = self.drop(Ht)
        y_hat = self.out(Ht[:, :-1, :]).squeeze(-1)  # predict months 1..Tseq-1
        return F.softplus(y_hat)  # nonnegative

