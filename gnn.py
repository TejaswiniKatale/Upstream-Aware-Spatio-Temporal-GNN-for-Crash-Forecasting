def AccuracyAt20(y, yp):
    denom = np.sum(y > 0)
    if denom == 0:
        return np.nan
    thr = np.quantile(yp, 0.8)
    return np.sum((y > 0) & (yp >= thr)) / denom

def RecallAt20(y, yp):
    K = max(1, int(0.2 * len(y)))
    return len(set(np.argsort(-y)[:K]) & set(np.argsort(-yp)[:K])) / K

# =========================================================
# 8. HYPERPARAMETER TUNING (SAFE)
# =========================================================
param_grid = {
    "lr": [5e-4, 1e-3, 2e-3],
    "dropout": [0.2, 0.3],
    "gnn": [32, 64],
    "gru": [32, 64],
    "wcap": [5.0, 10.0]
}

results = []

for lr, d, gnn, gru, wc in itertools.product(
    param_grid["lr"],
    param_grid["dropout"],
    param_grid["gnn"],
    param_grid["gru"],
    param_grid["wcap"]
):
    print("Running:", lr, d, gnn, gru, wc)

    model = STGNN(F_dim, gnn, gru, d).to(device)
    opt = torch.optim.Adam(model.parameters(), lr=lr)

    best_val = float("inf")
    best_state = {k: v.cpu() for k, v in model.state_dict().items()}  # ✅ FIX

    for _ in range(10):
        model.train()
        yp = model(X_torch[:, :train_T])
        yt = y_torch[:, 1:train_T]

        w = torch.clamp(1 + yt, max=wc)
        loss = torch.mean(w * (yp - yt) ** 2)

        opt.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
        opt.step()

        model.eval()
        with torch.no_grad():
            vp = model(X_torch[:, :train_T + val_T])
            val = F.mse_loss(vp[:, 23:29], y_torch[:, 24:30])

            if torch.isfinite(val) and val.item() < best_val:
                best_val = val.item()
                best_state = {k: v.cpu() for k, v in model.state_dict().items()}

    model.load_state_dict(best_state)

    with torch.no_grad():
        yp_all = model(X_torch).cpu().numpy()

    maes, accs, recs = [], [], []
    for m in range(30, 36):
        maes.append(np.mean(np.abs(y[:, m] - yp_all[:, m-1])))
        accs.append(AccuracyAt20(y[:, m], yp_all[:, m-1]))
        recs.append(RecallAt20(y[:, m], yp_all[:, m-1]))

    results.append({
        "lr": lr,
        "dropout": d,
        "gnn_dim": gnn,
        "gru_dim": gru,
        "weight_cap": wc,
        "MAE": np.mean(maes),
        "Accuracy@20": np.mean(accs),
        "Recall@20": np.mean(recs)
    })

# =========================================================
