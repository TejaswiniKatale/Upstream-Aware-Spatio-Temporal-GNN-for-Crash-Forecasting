def AccuracyAt20(y_true, y_pred):
    """
    Accuracy@20 (Hotspot hit rate)
#     % of crash-positive segments captured in top-20% predicted risk
    """
    denom = np.sum(y_true > 0)
    if denom == 0:
        return np.nan
    thr = np.quantile(y_pred, 0.8)
    return float(np.sum((y_true > 0) & (y_pred >= thr)) / denom)


def RecallAt20(y_true, y_pred):
    """
    Recall@20
    Overlap between top-20% true and predicted risky segments
    """
    K = max(1, int(0.2 * len(y_true)))
    top_true = set(np.argsort(-y_true)[:K])
    top_pred = set(np.argsort(-y_pred)[:K])
    return float(len(top_true & top_pred) / K)

