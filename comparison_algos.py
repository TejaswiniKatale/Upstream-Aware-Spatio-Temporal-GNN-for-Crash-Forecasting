assert T == 36, "Expected 36 months."

seg2idx = {s:i for i,s in enumerate(segments)}
mon2idx = {m:i for i,m in enumerate(months)}

# =========================
# 2. CHOOSE NUMERIC FEATURES
# =========================
# We will use ALL numeric variables except the target, plus a crash-history channel.
# Input at month t predicts target at month t+1.
numeric_cols = [
    c for c in df.select_dtypes(include=[np.number]).columns
    if c not in ["TOTAL_CRASHES", "YEAR_QUARTER", "YEAR_HALF"]
]

# Fill missing
df[numeric_cols] = df[numeric_cols].fillna(0.0)
