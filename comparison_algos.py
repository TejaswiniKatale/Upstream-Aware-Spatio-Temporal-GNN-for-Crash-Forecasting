def rolling_arima(y_seg, min_hist=3):
    """
    Rolling one-step-ahead ARIMA(1,0,0)
    Returns predictions for months 1..35
    """
    preds = np.full(T-1, np.nan)

    for m in range(1, T):
        hist = y_seg[:m]

        # fallback: too short or constant
        if m < min_hist or np.allclose(hist, hist[0]):
            preds[m-1] = hist.mean()
            continue

        try:
            model = ARIMA(hist, order=(1,0,0), trend="c")
            res = model.fit()
            preds[m-1] = res.forecast(1)[0]
        except:
            preds[m-1] = hist.mean()

    return np.clip(preds, 0, None)

