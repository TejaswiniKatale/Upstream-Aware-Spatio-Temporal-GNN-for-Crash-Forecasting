# =========================
# 3. BUILD X (N,T,F) AND y (N,T)
# =========================
X = np.zeros((N, T, F_dim), dtype=np.float32)
y = np.zeros((N, T), dtype=np.float32)

for _, r in df.iterrows():
    i = seg2idx[r["SEGMENT_KEY"]]
    t = mon2idx[r["YEAR_MONTH"]]
    X[i, t, :F_num] = r[numeric_cols].values.astype(np.float32)
    X[i, t, F_num]  = float(r["TOTAL_CRASHES"])   # crash history at month t
    y[i, t]         = float(r["TOTAL_CRASHES"])

# =========================
# 4. MAKE SUPERVISED PAIRS: (seg, month t) -> y_{t+1}
# Target months m = 1..35
# =========================
# For each target month m, input month is (m-1).
# We keep month index as the TARGET month index m (1..35) for month-wise metrics.

pairs_X = []
pairs_y = []
pairs_seg = []
pairs_m = []  # target month index m

for i in range(N):
    for m in range(1, T):  # 1..35
        pairs_X.append(X[i, m-1, :])
        pairs_y.append(y[i, m])
        pairs_seg.append(i)
        pairs_m.append(m)

pairs_X = np.asarray(pairs_X, dtype=np.float32)  # (N*(T-1), F)
pairs_y = np.asarray(pairs_y, dtype=np.float32)  # (N*(T-1),)
pairs_seg = np.asarray(pairs_seg, dtype=np.int32)
pairs_m = np.asarray(pairs_m, dtype=np.int32)

# =========================
# 5. SPLIT BY TARGET MONTH (NO FUTURE PEEK)
# train: m=1..23, val: 24..29, test: 30..35
# =========================
train_mask = (pairs_m >= 1)  & (pairs_m <= 23)
val_mask   = (pairs_m >= 24) & (pairs_m <= 29)
test_mask  = (pairs_m >= 30) & (pairs_m <= 35)

X_train, y_train = pairs_X[train_mask], pairs_y[train_mask]
X_val,   y_val   = pairs_X[val_mask],   pairs_y[val_mask]
X_test,  y_test  = pairs_X[test_mask],  pairs_y[test_mask]

seg_train, m_train = pairs_seg[train_mask], pairs_m[train_mask]
seg_val,   m_val   = pairs_seg[val_mask],   pairs_m[val_mask]
seg_test,  m_test  = pairs_seg[test_mask],  pairs_m[test_mask]

print("Samples | train:", len(X_train), "val:", len(X_val), "test:", len(X_test))

# =========================
# 6. STANDARDIZE FEATURES (FIT ON TRAIN ONLY)
# =========================
mu = X_train.mean(axis=0, keepdims=True)
sd = X_train.std(axis=0, keepdims=True) + 1e-6

def zscore(a):
    return (a - mu) / sd

X_train_s = zscore(X_train)
X_val_s   = zscore(X_val)
X_test_s  = zscore(X_test)

# =========================
# 7. DATASET + DATALOADER
# =========================
class PairDataset(Dataset):
    def __init__(self, X, y):
        self.X = torch.from_numpy(X).float()
        self.y = torch.from_numpy(y).float().view(-1, 1)
    def __len__(self):
        return self.X.size(0)
    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]

batch_size = 4096  # T4 friendly; reduce if OOM
train_loader = DataLoader(PairDataset(X_train_s, y_train), batch_size=batch_size, shuffle=True, drop_last=False)
val_loader   = DataLoader(PairDataset(X_val_s,   y_val),   batch_size=batch_size, shuffle=False, drop_last=False)

# =========================
# 8. SdAE MODEL (Denoising AE + Regressor)
# =========================
class SdAE(nn.Module):
    def __init__(self, in_dim, h1=256, h2=128, z=64, dropout=0.1):
        super().__init__()
        # Encoder
        self.enc = nn.Sequential(
            nn.Linear(in_dim, h1),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(h1, h2),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(h2, z),
            nn.ReLU()
        )
        # Decoder (for AE pretrain)
        self.dec = nn.Sequential(
            nn.Linear(z, h2),
            nn.ReLU(),
            nn.Linear(h2, h1),
            nn.ReLU(),
            nn.Linear(h1, in_dim)
        )
        # Regression head
        self.reg = nn.Sequential(
            nn.Linear(z, 64),
            nn.ReLU(),
            nn.Linear(64, 1)
        )

    def encode(self, x):
        return self.enc(x)

    def reconstruct(self, x):
        z = self.encode(x)
        return self.dec(z)

    def forward(self, x):
        z = self.encode(x)
        out = self.reg(z)
        return F.softplus(out)  # ensure non-negative crash predictions

model = SdAE(in_dim=F_dim, h1=256, h2=128, z=64, dropout=0.1).to(device)

# =========================
# 9. DENOISING FUNCTION
# =========================
def add_noise(x, p_mask=0.15, sigma=0.05):
    # x: standardized features
    # masking noise + small gaussian noise
    if p_mask > 0:
        mask = (torch.rand_like(x) < p_mask).float()
        x = x * (1 - mask)
    if sigma > 0:
        x = x + sigma * torch.randn_like(x)
    return x

# =========================
# 10. STAGE 1: AE PRETRAIN (FAST)
# =========================
ae_epochs = 10
ae_opt = torch.optim.Adam(list(model.enc.parameters()) + list(model.dec.parameters()), lr=1e-3)

best_ae = float("inf")
best_ae_state = None
patience = 3
bad = 0

for epoch in range(1, ae_epochs + 1):
    model.train()
    tr_losses = []
    for xb, _ in train_loader:
        xb = xb.to(device)
        xb_noisy = add_noise(xb, p_mask=0.15, sigma=0.05)

        recon = model.reconstruct(xb_noisy)
        loss = F.mse_loss(recon, xb)

        ae_opt.zero_grad()
        loss.backward()
        ae_opt.step()

        tr_losses.append(loss.item())

    model.eval()
    with torch.no_grad():
        va_losses = []
        for xb, _ in val_loader:
            xb = xb.to(device)
            xb_noisy = add_noise(xb, p_mask=0.15, sigma=0.05)
            recon = model.reconstruct(xb_noisy)
            va_losses.append(F.mse_loss(recon, xb).item())
        val_loss = float(np.mean(va_losses))

    print(f"[AE] Epoch {epoch:02d} | TrainRecon={np.mean(tr_losses):.6f} | ValRecon={val_loss:.6f}")

    if val_loss < best_ae - 1e-6:
        best_ae = val_loss
        best_ae_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        bad = 0
    else:
        bad += 1
        if bad >= patience:
            print(f"[AE] Early stop at epoch {epoch:02d} | Best ValRecon={best_ae:.6f}")
            break

if best_ae_state is not None:
    model.load_state_dict(best_ae_state)

# =========================
# 11. STAGE 2: REGRESSION FINETUNE (ENCODER + REG HEAD)
# =========================
reg_epochs = 20
opt = torch.optim.Adam(list(model.enc.parameters()) + list(model.reg.parameters()), lr=1e-3)

best_val = float("inf")
best_state = None
bad = 0
patience = 4

for epoch in range(1, reg_epochs + 1):
    model.train()
    tr_losses = []
    for xb, yb in train_loader:
        xb = xb.to(device)
        yb = yb.to(device)

        pred = model(xb)
        loss = F.mse_loss(pred, yb)

        opt.zero_grad()
        loss.backward()
        opt.step()
        tr_losses.append(loss.item())

    model.eval()
    with torch.no_grad():
        va_losses = []
        for xb, yb in val_loader:
            xb = xb.to(device)
            yb = yb.to(device)
            pred = model(xb)
            va_losses.append(F.mse_loss(pred, yb).item())
        val_loss = float(np.mean(va_losses))

    print(f"[REG] Epoch {epoch:02d} | TrainMSE={np.mean(tr_losses):.6f} | ValMSE={val_loss:.6f}")

    if val_loss < best_val - 1e-6:
        best_val = val_loss
        best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        bad = 0
    else:
        bad += 1
        if bad >= patience:
            print(f"[REG] Early stop at epoch {epoch:02d} | Best ValMSE={best_val:.6f}")
            break

if best_state is not None:
    model.load_state_dict(best_state)

save_path = "/content/drive/MyDrive/Upstream/sdae_houston_36month.pth"
torch.save(model.state_dict(), save_path)
