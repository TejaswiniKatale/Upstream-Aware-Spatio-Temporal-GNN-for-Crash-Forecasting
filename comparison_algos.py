# =========================================================
# SdAE (Stacked Denoising AutoEncoder) BASELINE – FULL CODE
# Predict next month y_{t+1} using features at month t
# Split by TARGET MONTH: train (1..23), val (24..29), test (30..35)
# Metrics: MAE, RMSE, MAPE, Accuracy@20, Recall@20, ZeroRate
