class SpatialMean(nn.Module):
    def __init__(self, dim, neighbors):
        super().__init__()
        self.neighbors = neighbors
        self.lin = nn.Linear(dim*2, dim)

    def forward(self, h):
        N, d = h.shape
        agg = torch.zeros_like(h)
        for i in range(N):
            if len(self.neighbors[i]) > 0:
                agg[i] = h[self.neighbors[i]].mean(dim=0)
        return F.relu(self.lin(torch.cat([h, agg], dim=1)))

class STNB_GNN(nn.Module):
    def __init__(self, Fdim, gnn_dim=64, gru_dim=64, gnn_layers=2):
        super().__init__()
        self.in_proj = nn.Linear(Fdim, gnn_dim)
        self.gnn = nn.ModuleList([SpatialMean(gnn_dim, neighbors) for _ in range(gnn_layers)])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)
        self.mu_head = nn.Linear(gru_dim, 1)
        self.log_theta = nn.Parameter(torch.tensor(0.0))  # dispersion

    def forward(self, Xseq):
        Nn, Tseq, _ = Xseq.shape
        Hs = []
        for t in range(Tseq):
            h = F.relu(self.in_proj(Xseq[:, t, :]))
            for layer in self.gnn:
                h = layer(h)
            Hs.append(h.unsqueeze(1))
        Hs = torch.cat(Hs, dim=1)
        H, _ = self.gru(Hs)
        mu = F.softplus(self.mu_head(H[:, :-1, :])).squeeze(-1)
        theta = torch.exp(self.log_theta)
        return mu, theta

def nb_nll(y, mu, theta):
    return torch.mean(
        torch.lgamma(y + theta) - torch.lgamma(theta) - torch.lgamma(y + 1)
        + theta * torch.log(theta / (theta + mu))
        + y * torch.log(mu / (theta + mu))
    ) * -1

