# 12. METRIC FUNCTIONS (MONTH-WISE)
# =========================
def MAE(yt, yp):
    return float(np.mean(np.abs(yt - yp)))

def RMSE(yt, yp):
    return float(np.sqrt(np.mean((yt - yp) ** 2)))

def MAPE(yt, yp, eps=1e-6):
    return float(np.mean(np.abs((yt - yp) / np.maximum(yt, eps))))

def AccHR20(yt, yp):
    denom = np.sum(yt > 0)
    if denom == 0:
        return np.nan
    thr = np.quantile(yp, 0.8)
    return float(np.sum((yt > 0) & (yp >= thr)) / denom)

def Recall20(yt, yp):
    Nn = yt.shape[0]
    K = max(1, int(0.2 * Nn))
    top_true = np.argsort(-yt)[:K]
    top_pred = np.argsort(-yp)[:K]
    return float(len(set(top_true) & set(top_pred)) / K)

def ZeroRate(yp):
    return float(np.mean(yp < 1e-6))

# =========================
# 13. PREDICT FOR ALL MONTHS (m=1..35) AND COMPUTE MONTH-WISE METRICS
# =========================
# We will predict using the paired inputs we already built (pairs_X),
