# 4. GRAPH CONV LAYER (MEAN AGGREGATION)
# =========================================================
class GraphConv(nn.Module):
    def __init__(self, in_dim, out_dim, neighbors):
        super().__init__()
        self.neighbors = neighbors
        self.W_self = nn.Linear(in_dim, out_dim)
        self.W_nei  = nn.Linear(in_dim, out_dim)

    def forward(self, h):
        N, d = h.shape
        agg = torch.zeros((N, d), device=h.device)
        for i in range(N):
            if len(self.neighbors[i]) > 0:
                agg[i] = h[self.neighbors[i]].mean(dim=0)
        return F.relu(self.W_self(h) + self.W_nei(agg))

# =========================================================
# 5. HETERO-CONVLSTM MODEL (NO ROUTE)
# =========================================================
class HeteroConvLSTM(nn.Module):
    def __init__(self, Fdim, gnn_dim=64, gnn_layers=2, lstm_dim=64):
        super().__init__()
        self.input_proj = nn.Linear(Fdim, gnn_dim)
        self.gnn = nn.ModuleList([
            GraphConv(gnn_dim, gnn_dim, neighbors)
            for _ in range(gnn_layers)
        ])
        self.lstm = nn.LSTM(gnn_dim, lstm_dim, batch_first=True)
        self.out = nn.Linear(lstm_dim, 1)

    def spatial_encode(self, x_t):
        h = F.relu(self.input_proj(x_t))
        for layer in self.gnn:
            h = layer(h)
        return h

    def forward(self, Xseq):
        # Xseq: (N, Tseq, F)
        H_list = []
        for t in range(Xseq.shape[1]):
            H_list.append(self.spatial_encode(Xseq[:, t, :]).unsqueeze(1))
        H = torch.cat(H_list, dim=1)
        H_lstm, _ = self.lstm(H)
        yhat = self.out(H_lstm[:, :-1, :]).squeeze(-1)
        return F.softplus(yhat)

