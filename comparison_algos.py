class GraphSAGELayer(nn.Module):
    def __init__(self, dim, neighbors, dropout=0.0):
        super().__init__()
        self.neighbors = neighbors
        self.lin = nn.Linear(dim * 2, dim)
        self.dropout = nn.Dropout(dropout)

    def forward(self, h):
        Nn, d = h.shape
        agg = torch.zeros((Nn, d), device=h.device)

        for i in range(Nn):
            nei = self.neighbors[i]
            if len(nei) > 0:
                agg[i] = h[nei].mean(dim=0)

        out = self.lin(torch.cat([h, agg], dim=1))
        out = F.relu(out)
        return self.dropout(out)

class STGGNN(nn.Module):
    def __init__(self, Fdim, gnn_dim=64, gnn_layers=2, gru_dim=64, dropout=0.1):
        super().__init__()
        self.in_proj = nn.Linear(Fdim, gnn_dim)
        self.sage = nn.ModuleList([
            GraphSAGELayer(gnn_dim, neighbors, dropout=dropout)
            for _ in range(gnn_layers)
        ])
        self.gru = nn.GRU(gnn_dim, gru_dim, batch_first=True)
        self.out = nn.Linear(gru_dim, 1)

    def spatial_encode(self, x_t):
        h = F.relu(self.in_proj(x_t))
        for layer in self.sage:
            h = layer(h)
        return h

    def forward(self, Xseq):
        # Xseq: (N, Tseq, F)
        Nn, Tseq, _ = Xseq.shape
        H_list = []
        for t in range(Tseq):
            H_list.append(self.spatial_encode(Xseq[:, t, :]).unsqueeze(1))
        Hs = torch.cat(H_list, dim=1)            # (N, Tseq, gnn_dim)
        H, _ = self.gru(Hs)                      # (N, Tseq, gru_dim)
        yhat = self.out(H[:, :-1, :]).squeeze(-1)  # (N, Tseq-1)
        return F.softplus(yhat)                  # non-negative

