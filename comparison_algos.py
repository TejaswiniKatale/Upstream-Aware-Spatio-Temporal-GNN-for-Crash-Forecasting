for k in range(all_pred.shape[0]):
    i = pairs_seg[k]
    m = pairs_m[k]          # 1..35
    y_pred_sdae[i, m-1] = all_pred[k]

# Month-wise metrics for ALL months (prediction months 1..35)
rows = []
for m in range(1, T):  # 1..35
    yt = y[:, m]           # actual at target month m
    yp = y_pred_sdae[:, m-1]

    rows.append({
        "YEAR_MONTH": months[m],
        "MONTH_INDEX": m,
        "MAE": MAE(yt, yp),
        "RMSE": RMSE(yt, yp),
        "MAPE": MAPE(yt, yp),
        "Accuracy@20": AccHR20(yt, yp),
        "Recall@20": Recall20(yt, yp),
        "ZeroRate": ZeroRate(yp),
        "SPLIT": ("TRAIN" if m <= 23 else ("VAL" if m <= 29 else "TEST"))
    })

sdae_monthly_df = pd.DataFrame(rows)

print("\nPreview month-wise metrics:")
print(sdae_monthly_df.head(10))

# =========================
# 14. FINAL TEST METRICS (AVG OVER TEST MONTHS)
# =========================
test_df = sdae_monthly_df[sdae_monthly_df["SPLIT"] == "TEST"]

final_metrics = {
    "MAE": test_df["MAE"].mean(),
    "RMSE": test_df["RMSE"].mean(),
    "MAPE": test_df["MAPE"].mean(),
    "Accuracy@20": test_df["Accuracy@20"].mean(),
    "Recall@20": test_df["Recall@20"].mean(),
    "ZeroRate": test_df["ZeroRate"].mean(),
}

print("\n===== FINAL SdAE METRICS (TEST AVG) =====")
for k, v in final_metrics.items():
    print(f"{k:12s}: {v:.6f}")

# =========================
# 15. BEST PERFORMING MONTH (BY MAE) + ALL VALUES
# =========================
best_row = sdae_monthly_df.loc[sdae_monthly_df["MAE"].idxmin()]

print("\n===== BEST PERFORMING MONTH (SdAE) =====")
for col in best_row.index:
    print(f"{col:14s}: {best_row[col]}")

# =========================
# 16. SAVE OUTPUTS
# =========================
metrics_path = "/content/drive/MyDrive/Upstream/SdAE_monthwise_metrics_36months.csv"
sdae_monthly_df.to_csv(metrics_path, index=False)
print("\nSaved month-wise metrics:", metrics_path)

# Optional: save per-segment month-wise predictions (N × 35) as CSV (wide)
pred_wide = pd.DataFrame(y_pred_sdae, columns=[months[m].strftime("%Y-%m") for m in range(1, T)])
pred_wide.insert(0, "SEGMENT_KEY", segments)

